#!/bin/bash

# Define the pcap prefix used in your script
PCAP_PREFIX="rip-simple-routing"

echo "===================================================================="
echo "          RIP Routing Overhead & Traffic Analysis Tool"
echo "===================================================================="
echo "Searching for .pcap files matching prefix: ${PCAP_PREFIX}*.pcap"
echo ""

# Check if any matching pcap files exist
files=( ${PCAP_PREFIX}*.pcap )
if [ ! -e "${files[0]}" ]; then
    echo "Error: No pcap files found starting with '${PCAP_PREFIX}'."
    echo "Make sure you have run the simulation first."
    exit 1
fi

grand_total_packets=0
grand_total_rip=0

# Loop through each pcap file generated by the simulation
for pcap_file in "${files[@]}"; do
    # Count total packets in the pcap file
    total_packets=$(tcpdump -n -r "$pcap_file" 2>/dev/null | wc -l)
    
    # Count RIP packets (UDP port 520)
    rip_count=$(tcpdump -n -r "$pcap_file" udp port 520 2>/dev/null | wc -l)
    
    # Calculate percentage safely (handling division by zero if a pcap is completely empty)
    if [ "$total_packets" -gt 0 ]; then
        # Using awk for floating-point percentage calculation
        percentage=$(awk "BEGIN {printf \"%.2f\", ($rip_count / $total_packets) * 100}")
    else
        percentage="0.00"
    fi
    
    echo "File: $pcap_file"
    echo "  -> Total Packets : $total_packets"
    echo "  -> RIP Packets   : $rip_count"
    echo "  -> RIP Overhead  : ${percentage}%"
    echo "------------------------------------------------------------------"
    
    # Accumulate grand totals
    grand_total_packets=$((grand_total_packets + total_packets))
    grand_total_rip=$((grand_total_rip + rip_count))
done

# Calculate overall grand total percentage
if [ "$grand_total_packets" -gt 0 ]; then
    grand_percentage=$(awk "BEGIN {printf \"%.2f\", ($grand_total_rip / $grand_total_packets) * 100}")
else
    grand_percentage="0.00"
fi

echo "===================================================================="
echo "                         GRAND TOTAL SUMMARY"
echo "===================================================================="
echo "Total Network Packets Across All Interfaces : $grand_total_packets"
echo "Total RIP Routing Packets                   : $grand_total_rip"
echo "Overall RIP Routing Overhead                : ${grand_percentage}%"
echo "===================================================================="
