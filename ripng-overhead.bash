#!/bin/bash

# Define the pcap prefix used in your script
PCAP_PREFIX="ripng-simple-routing"

echo "===================================================================="
echo "          RIPng Routing Overhead & ICMPv6 Traffic Analyzer"
echo "===================================================================="
echo "Searching for .pcap files matching prefix: ${PCAP_PREFIX}*.pcap"
echo ""

# Check if any matching pcap files exist
files=( ${PCAP_PREFIX}*.pcap )
if [ ! -e "${files[0]}" ]; then
    echo "Error: No pcap files found starting with '${PCAP_PREFIX}'."
    echo "Make sure you have run the simulation first."
    exit 1
fi

grand_total_packets=0
grand_total_rip=0
grand_total_icmp6=0

# Loop through each pcap file generated by the simulation
for pcap_file in "${files[@]}"; do
    # Count total packets in the pcap file
    total_packets=$(tcpdump -n -r "$pcap_file" 2>/dev/null | wc -l)
    
    # Count RIPng packets (UDP port 521)
    rip_count=$(tcpdump -n -r "$pcap_file" udp port 521 2>/dev/null | wc -l)
    
    # Count ICMPv6 packets (includes neighbor discovery, pings, and destination unreachable)
    icmp6_count=$(tcpdump -n -r "$pcap_file" icmp6 2>/dev/null | wc -l)
    
    # Calculate percentages safely (handling division by zero)
    if [ "$total_packets" -gt 0 ]; then
        rip_percentage=$(awk "BEGIN {printf \"%.2f\", ($rip_count / $total_packets) * 100}")
        icmp6_percentage=$(awk "BEGIN {printf \"%.2f\", ($icmp6_count / $total_packets) * 100}")
    else
        rip_percentage="0.00"
        icmp6_percentage="0.00"
    fi
    
    echo "File: $pcap_file"
    echo "  -> Total Packets   : $total_packets"
    echo "  -> RIPng Packets   : $rip_count (${rip_percentage}%)"
    echo "  -> ICMPv6 Packets  : $icmp6_count (${icmp6_percentage}%)"
    echo "------------------------------------------------------------------"
    
    # Accumulate grand totals
    grand_total_packets=$((grand_total_packets + total_packets))
    grand_total_rip=$((grand_total_rip + rip_count))
    grand_total_icmp6=$((grand_total_icmp6 + icmp6_count))
done

# Calculate overall grand total percentages
if [ "$grand_total_packets" -gt 0 ]; then
    grand_rip_percentage=$(awk "BEGIN {printf \"%.2f\", ($grand_total_rip / $grand_total_packets) * 100}")
    grand_icmp6_percentage=$(awk "BEGIN {printf \"%.2f\", ($grand_total_icmp6 / $grand_total_packets) * 100}")
else
    grand_rip_percentage="0.00"
    grand_icmp6_percentage="0.00"
fi

echo "===================================================================="
echo "                         GRAND TOTAL SUMMARY"
echo "===================================================================="
echo "Total Network Packets Across All Interfaces : $grand_total_packets"
echo "Total RIPng Routing Packets                 : $grand_total_rip (${grand_rip_percentage}%)"
echo "Total ICMPv6 Packets (Pings/ND/Unreachable)   : $grand_total_icmp6 (${grand_icmp6_percentage}%)"
echo "===================================================================="
